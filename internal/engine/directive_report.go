package engine

import (
	"cmp"
	"encoding/json"
	"fmt"
	"slices"
	"strings"

	"github.com/frithuz/mdchk/internal/result"
)

func appendDirectiveNote(out *result.Result, path string, snap result.Snapshot, projection *projector, note DirectiveNote) error {
	if err := projection.checkpoint(int64(len(note.Message)) + 1); err != nil {
		return err
	}
	fields := map[string]bool{}
	for _, origin := range note.Restrictions {
		if err := projection.checkpoint(int64(len(origin.PropertyPath)) + 1); err != nil {
			return err
		}
		if origin.PropertyPath != "" {
			fields[origin.PropertyPath] = true
		}
	}
	names := make([]string, 0, len(fields))
	for name := range fields {
		names = append(names, name)
	}
	slices.Sort(names)
	message := note.Message
	if len(names) > 0 {
		message += "; restricted by " + strings.Join(names, ", ")
	}
	record := result.Note{ID: fmt.Sprintf("note-%d", len(out.Notes)+1), Code: note.Code, Message: message, Path: path, Rule: note.Rule}
	if note.Span.Present() {
		a, err := projection.position(note.Span.Start())
		if err != nil {
			return err
		}
		b, err := projection.position(note.Span.End())
		if err != nil {
			return err
		}
		record.Range = &result.Range{Start: a, End: b}
		record.ByteRange = &result.ByteRange{Start: note.Span.Start(), End: note.Span.End()}
		record.Snapshot = &snap
	}
	raw, _ := json.Marshal(record)
	out.Notes = append(out.Notes, raw)
	return nil
}
func appendSuppressed(out *result.Result, diagnostic result.Diagnostic, owner int) {
	kind := "configuration"
	if owner >= 0 {
		kind = "directive"
	}
	record := result.SuppressedDiagnostic{Diagnostic: diagnostic, SuppressedBy: result.Suppression{Kind: kind}}
	raw, _ := json.Marshal(record)
	out.SuppressedDiagnostics = append(out.SuppressedDiagnostics, raw)
}

// Canonicalize serialized observations independently of callback order. No
// cross-record directive IDs are generated by the lint subset.
func finalizeDirectiveRecords(out *result.Result) {
	type orderedNote struct {
		record result.Note
		key    string
	}
	notes := make([]orderedNote, len(out.Notes))
	for i, raw := range out.Notes {
		_ = json.Unmarshal(raw, &notes[i].record)
		notes[i].record.ID = ""
		key, _ := json.Marshal(notes[i].record)
		notes[i].key = string(key)
	}
	slices.SortFunc(notes, func(a, b orderedNote) int {
		if c := cmp.Compare(a.record.Path, b.record.Path); c != 0 {
			return c
		}
		if c := compareRange(a.record.Range, b.record.Range); c != 0 {
			return c
		}
		if c := cmp.Compare(a.record.Rule, b.record.Rule); c != 0 {
			return c
		}
		if c := cmp.Compare(a.record.Code, b.record.Code); c != 0 {
			return c
		}
		return strings.Compare(a.key, b.key)
	})
	for i, n := range notes {
		n.record.ID = fmt.Sprintf("note-%d", i+1)
		out.Notes[i], _ = json.Marshal(n.record)
	}
	type orderedSuppression struct {
		record result.SuppressedDiagnostic
		key    string
	}
	suppressed := make([]orderedSuppression, len(out.SuppressedDiagnostics))
	for i, raw := range out.SuppressedDiagnostics {
		_ = json.Unmarshal(raw, &suppressed[i].record)
		suppressed[i].record.Diagnostic.ID = ""
		key, _ := json.Marshal(suppressed[i].record)
		suppressed[i].key = string(key)
	}
	slices.SortFunc(suppressed, func(a, b orderedSuppression) int {
		if c := cmp.Compare(a.record.Diagnostic.Path, b.record.Diagnostic.Path); c != 0 {
			return c
		}
		if c := cmp.Compare(a.record.Diagnostic.ByteRange.Start, b.record.Diagnostic.ByteRange.Start); c != 0 {
			return c
		}
		if c := cmp.Compare(a.record.Diagnostic.Rule, b.record.Diagnostic.Rule); c != 0 {
			return c
		}
		return strings.Compare(a.key, b.key)
	})
	for i, s := range suppressed {
		s.record.Diagnostic.ID = fmt.Sprintf("suppressed-diagnostic-%d", i+1)
		out.SuppressedDiagnostics[i], _ = json.Marshal(s.record)
	}
}
