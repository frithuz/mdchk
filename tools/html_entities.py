#!/usr/bin/env python3
"""Regenerate or check the strict CommonMark named-entity table offline."""

import argparse
import hashlib
import json
from pathlib import Path
import subprocess


ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "internal/parser/testdata/html5/entities.json"
OUTPUT = ROOT / "internal/parser/entities_table.go"
SOURCE_SHA256 = "d741d877ac77c4194c4ad526b5b4a19aef8dfe411ab840a466891cdbb9f362e6"


def generate():
    data = SOURCE.read_bytes()
    if hashlib.sha256(data).hexdigest() != SOURCE_SHA256:
        raise ValueError("pinned entities.json hash mismatch")
    entries = {k: v for k, v in json.loads(data).items() if k.endswith(";")}
    lines = ["// Code generated by tools/html_entities.py; DO NOT EDIT.",
             "// Copyright WHATWG (Apple, Google, Mozilla, Microsoft).",
             "// Source, attribution and license: testdata/html5/.",
             "package parser", "",
             "const maxEntityToken = %d" % max(map(len, entries)), "",
             "var namedEntities = map[string]string{"]
    for name, value in sorted(entries.items()):
        points = value["codepoints"]
        if "".join(chr(c) for c in points) != value["characters"]:
            raise ValueError("inconsistent entity code points")
        escaped = "".join("\\U%08x" % c for c in points)
        lines.append('"%s": "%s",' % (name, escaped))
    lines.append("}")
    return subprocess.check_output(["gofmt"], input=("\n".join(lines) + "\n").encode())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if OUTPUT.read_bytes() != generated:
            raise SystemExit("named-entity table differs from pinned source")
        print("checked all 2125 semicolon-terminated HTML5 named entities")
    else:
        OUTPUT.write_bytes(generated)


if __name__ == "__main__":
    main()
