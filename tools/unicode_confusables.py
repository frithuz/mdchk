#!/usr/bin/env python3
"""Regenerate or check the pinned Unicode 17.0.0 ASCII-letter confusables table offline."""

import argparse
import hashlib
from pathlib import Path
import subprocess


ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "internal/confusables/testdata/unicode/17.0.0"
OUTPUT = ROOT / "internal/confusables/table.go"
SOURCES = {
    "confusables.txt": ("091c7f82fc39ef208faf8f94d29c244de99254675e09de163160c810d13ef22a", 745683),
    "LICENSE.txt": ("e7a93b009565cfce55919a381437ac4db883e9da2126fa28b91d12732bc53d96", 1995),
}


def read_sources():
    texts = {}
    for name, (digest, size) in SOURCES.items():
        data = (DATA / name).read_bytes()
        # Pinned Unicode 17.0.0 sources; never fetch or use host Unicode data.
        if len(data) != size or hashlib.sha256(data).hexdigest() != digest:
            raise SystemExit("pinned %s hash mismatch" % name)
        texts[name] = data.decode("utf-8")
    return texts


def ascii_letters(text):
    """Direct mappings whose target is a nonempty sequence of ASCII letters only."""
    table = {}
    for line in text.splitlines():
        fields = [f.strip() for f in line.split("#", 1)[0].split(";")]
        if len(fields) < 3:
            continue
        source = int(fields[0], 16)
        target = [int(c, 16) for c in fields[1].split()]
        if source in table:
            raise SystemExit("confusables.txt repeats U+%04X" % source)
        if target and all(0x41 <= c <= 0x5A or 0x61 <= c <= 0x7A for c in target):
            table[source] = "".join(chr(c) for c in target)
    return table


def generate():
    texts = read_sources()
    lines = ["// Code generated by tools/unicode_confusables.py; DO NOT EDIT.",
             "// Unicode 17.0.0 confusables.txt direct mappings whose target is",
             "// solely ASCII letters A-Z and a-z.",
             "// Source and Unicode license: testdata/unicode/17.0.0/.",
             "", "package confusables", "",
             "// asciiLetters is sorted by source code point.",
             "var asciiLetters = []entry{"]
    lines += ['{0x%X, "%s"},' % (c, m) for c, m in sorted(ascii_letters(texts["confusables.txt"]).items())]
    lines.append("}")
    return subprocess.check_output(["gofmt"], input=("\n".join(lines) + "\n").encode())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if OUTPUT.read_bytes() != generated:
            raise SystemExit("confusables table differs from pinned sources")
        print("checked Unicode 17.0.0 confusables table")
    else:
        OUTPUT.write_bytes(generated)


if __name__ == "__main__":
    main()
