#!/usr/bin/env python3
"""Regenerate or check the parser's full default Unicode case-fold mapping offline."""

import argparse
import hashlib
from pathlib import Path
import subprocess


ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "internal/parser/testdata/unicode/17.0.0/CaseFolding.txt"
OUTPUT = ROOT / "internal/parser/casefold_table.go"
SOURCE_SHA256 = "ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183"


def generate():
    data = SOURCE.read_bytes()
    # Pinned Unicode 17.0.0 source; never use the host Python Unicode database.
    if hashlib.sha256(data).hexdigest() != SOURCE_SHA256:
        raise ValueError("pinned CaseFolding.txt hash mismatch")
    lines = ["// Code generated by tools/unicode_casefold.py; DO NOT EDIT.",
             "// Unicode 17.0.0 full default folding (C + F, excluding S and T).",
             "// Source and Unicode license: testdata/unicode/17.0.0/.",
             "package parser", "", "var fullCaseFold = map[rune]string{"]
    for line in data.decode().splitlines():
        fields = line.split("#", 1)[0].split(";")
        if len(fields) < 3 or fields[1].strip() not in ("C", "F"):
            continue
        code = int(fields[0], 16)
        mapping = "".join("\\U%08x" % int(c, 16) for c in fields[2].split())
        lines.append('0x%X: "%s",' % (code, mapping))
    lines.append("}")
    return subprocess.check_output(["gofmt"], input=("\n".join(lines) + "\n").encode())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if OUTPUT.read_bytes() != generated:
            raise SystemExit("case-fold table differs from pinned source")
        print("checked Unicode 17.0.0 full default folding table")
    else:
        OUTPUT.write_bytes(generated)


if __name__ == "__main__":
    main()
